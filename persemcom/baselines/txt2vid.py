"""Txt2Vid-style baseline (paper Sec. V-B.5): speech -> text at the transmitter, compressed text over a
conventional digital link, text-to-speech at the receiver.

Transmitter ASR = the clean PerSemCom ASR model (no channel), so both systems start from the same
recognizer. Text is UTF-8 + zlib (level 9), sent over the LDPC/QPSK link. If any LDPC block of an
utterance fails, the compressed stream is corrupt and is dropped (empty text -> nothing is spoken), as
a real compressed-text link with a CRC would do. Speech is regenerated by the same speaker-conditioned
Tacotron 2 + knowledge base as PerSemCom, so the comparison isolates the transmission paradigm.
"""
import zlib
from typing import Tuple

import numpy as np

from persemcom.baselines.digital_link import DigitalLink


def text_to_bits(text: str) -> np.ndarray:
    return np.unpackbits(np.frombuffer(zlib.compress(text.encode("utf-8"), 9), dtype=np.uint8))


def bits_to_text(bits: np.ndarray) -> str:
    try:
        return zlib.decompress(np.packbits(bits).tobytes()).decode("utf-8")
    except (zlib.error, UnicodeDecodeError):
        return ""


def transmit_text(text: str, link: DigitalLink, snr_db: float, seed: int = 0) -> Tuple[str, int]:
    """Returns (received text, complex symbols used)."""
    bits = text_to_bits(text)
    res = link.send(bits, snr_db, seed=seed)
    received = bits_to_text(res.bits) if res.block_ok.all() else ""
    return received, res.n_symbols
